// Создаем объект MyClass, но храним указатель на него в переменной базового типа QObject
QObject *obj = new MyClass;

// Пытаемся безопасно "понизить" тип обратно до MyClass
MyClass *myObj = qobject_cast<MyClass*>(obj);

if (myObj) {
    // Приведение успешно: объект действительно является MyClass или его наследником
    myObj->mySlot(); 
} else {
    // Приведение не удалось: myObj будет равен nullptr
    // Это произойдет, если в obj на самом деле лежит другой класс
}

/* 
  ЧТО ЭТО И ЗАЧЕМ НУЖНО:

  1. Безопасность (в отличие от static_cast): 
     Если вы ошибетесь и попробуете привести объект к типу, которым он не является, 
     программа не "упадет" с ошибкой памяти, а просто вернет nullptr.

  2. Работа без RTTI: 
     qobject_cast не использует стандартный механизм C++ (dynamic_cast), 
     а опирается на метаданные Qt. Это работает быстрее и позволяет 
     использовать приведение типов даже там, где RTTI отключен.

  3. Проверка интерфейсов: 
     Часто используется при обработке сигналов. Например, в слоте можно 
     написать: `MyButton *btn = qobject_cast<MyButton*>(sender());`, 
     чтобы понять, какая именно кнопка вызвала этот код.

  4. Динамические плагины: 
     Позволяет проверить, реализует ли загруженный из библиотеки объект 
     нужный вам класс или интерфейс.
*/
