MyClass obj;
// Получаем указатель на метаобъект, который хранит всю информацию о структуре класса
const QMetaObject *meta = obj.metaObject();

// Выводит имя класса (как оно написано в коде)
qDebug() << "Имя класса:" << meta->className();

// Выводит количество свойств, объявленных через макрос Q_PROPERTY
qDebug() << "Количество свойств:" << meta->propertyCount();

// Проходим циклом по всем доступным свойствам
for (int i = 0; i < meta->propertyCount(); ++i) {
    // Получаем объект-описание конкретного свойства
    QMetaProperty prop = meta->property(i);
    // Выводим его название и тип данных (например, int, QString)
    qDebug() << "Свойство:" << prop.name() << "Тип:" << prop.typeName();
}

