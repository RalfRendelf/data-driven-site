// Создаем объект класса (у которого есть Q_OBJECT и метод mySlot)
MyClass obj;

// Вызываем метод "mySlot" по его строковому имени
QMetaObject::invokeMethod(&obj, "mySlot");

/* 
  ЧТО ЭТО И ЗАЧЕМ НУЖНО:

  1. Потокобезопасность (главная фишка): 
     Если добавить третий аргумент Qt::QueuedConnection, метод выполнится 
     в том потоке, в котором "живет" объект obj, даже если вы вызываете 
     его из другого потока. Это безопаснее, чем прямой вызов.

  2. Динамика: 
     Позволяет вызвать метод, имя которого вы знаете только в виде строки 
     (например, прочитали из конфига или скрипта), когда на этапе 
     компиляции прямой вызов невозможен.

  3. Отложенный вызов: 
     Можно заставить метод выполниться не прямо сейчас, а когда управление 
     вернется в цикл событий (event loop), чтобы не блокировать текущую логику.

  4. Инкапсуляция: 
     Позволяет вызвать слот, даже если у вас нет доступа к заголовочному файлу 
     класса MyClass (достаточно знать, что такой слот там есть).
*/
