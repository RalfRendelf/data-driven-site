// Создаем JSON-объект (аналог словаря или ассоциативного массива)
QJsonObject obj;

// Вставляем данные. В отличие от массива, здесь каждому значению соответствует уникальный ключ.
obj.insert("name", QJsonValue::fromVariant("Alice"));
obj.insert("age", QJsonValue::fromVariant(30));

// Оборачиваем объект в документ для последующей сериализации
QJsonDocument doc(obj);

// Преобразуем в текстовый формат (строку байт)
QByteArray jsonData = doc.toJson();

qDebug() << jsonData; // Результат: {"name": "Alice", "age": 30}

/* 
 * ДЛЯ ЧЕГО ЭТО НУЖНО (КОММЕНТАРИЙ ДЛЯ СТАТЬИ):
 *
 * 1. Структурированное хранение: 
 *    Использование ключей (названия полей) делает данные понятными. В отличие от массива, 
 *    порядок полей здесь не важен — доступ осуществляется по имени ключа.
 *
 * 2. Интеграция с Web-сервисами: 
 *    Объекты — это стандартный формат передачи сущностей (пользователь, товар, сообщение) 
 *    в REST API.
 *
 * 3. Гибкость (fromVariant): 
 *    Использование QJsonValue::fromVariant позволяет легко конвертировать стандартные 
 *    типы C++/Qt (QString, int, bool, double) в формат JSON без ручного приведения типов.
 *
 * 4. Читаемость vs Компактность: 
 *    Если вызвать doc.toJson(QJsonDocument::Compact), вы получите строку без лишних 
 *    пробелов и переносов, что идеально для минимизации сетевого трафика.
 */
