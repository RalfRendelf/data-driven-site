// Входные данные в формате JSON (используем R-string для удобства)
QByteArray jsonData = R"({"name": "Alice", "age": 30})";

// Создаем документ из строки байт
QJsonDocument doc = QJsonDocument::fromJson(jsonData);

// Важно проверить, что парсинг прошел успешно и в документе именно объект
if (doc.isObject()) {
    QJsonObject obj = doc.object();
    
    // Извлекаем значения по ключам и приводим их к нужным типам
    QString name = obj.value("name").toString();
    int age = obj.value("age").toInt();
    
    qDebug() << "Имя:" << name << "Возраст:" << age;
}

