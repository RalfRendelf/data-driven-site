// Создаем JSON-массив
QJsonArray arr;

// Наполняем его значениями. 
// Метод fromVariant удобен тем, что сам определяет тип данных (int, QString и т.д.)
arr.append(QJsonValue::fromVariant(1));
arr.append(QJsonValue::fromVariant(2));
arr.append(QJsonValue::fromVariant(3));

// Создаем JSON-документ на основе массива
QJsonDocument doc(arr);

// Преобразуем документ в текстовый формат (QByteArray)
// По умолчанию toJson() делает "красивый" вывод с отступами
QByteArray jsonData = doc.toJson();

qDebug() << jsonData; // Результат: [1, 2, 3]

