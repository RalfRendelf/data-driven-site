#include <iostream>
#include <regex> // Подключаем библиотеку для работы с регулярными выражениями
#include <string>

int main() {
    // Исходная строка для проверки
    std::string str = "hello123";

    // Создаем объект регулярного выражения (шаблон)
    // Разбор шаблона "^[a-z]+[0-9]+$":
    // ^      — начало строки. Гарантирует, что проверка идет с самого первого символа.
    // [a-z]+ — одна или более (+) строчных латинских букв.
    // [0-9]+ — одна или более (+) цифр.
    // $      — конец строки. Гарантирует, что после цифр в строке больше ничего нет.
    std::regex pattern("^[a-z]+[0-9]+$");

    // Функция regex_match проверяет, соответствует ли ВСЯ строка указанному шаблону
    if (std::regex_match(str, pattern)) {
        std::cout << "Строка соответствует шаблону" << std::endl;
    } else {
        std::cout << "Строка не соответствует шаблону" << std::endl;
    }

    return 0;
}
